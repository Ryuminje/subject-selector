// 사용 설명서의 단일 데이터 소스. hub.ts(허브 목록)와 같은 방식으로, 새 앱이나 새 설명을 넣을 때는
// 이 배열에 항목만 추가하면 /guide(요약본)와 /guide/<slug>(상세)가 알아서 그려집니다.
//
// 쓰는 규칙
// - 화면에 실제로 보이는 이름(탭·버튼·단계)을 그대로 씁니다. 이름이 바뀌면 여기도 고칩니다.
// - 쉬운 말로, 한 문장은 짧게. 처음 쓰는 선생님이 읽는다고 생각하고 씁니다.
// - 실제 학생 이름·학번은 절대 쓰지 않습니다(공개 저장소).
// - detail 이 없는 앱은 상세 페이지에 "준비 중" 안내가 뜨고 요약만 보입니다.
// - checkedAt 은 이 설명을 실제 화면과 맞춰 본 날짜입니다. 앱을 고치면 같이 갱신하세요.

export interface GuideStep {
  title: string;
  body: string;
}

export interface GuideFaq {
  q: string;
  a: string;
}

export interface GuideDetail {
  /** 한두 문장: 이 앱으로 무엇을 하나요 */
  intro: string;
  /** 시작 전에 준비할 것 */
  prepare: string[];
  /** 단계별 따라하기 */
  steps: GuideStep[];
  /** 같은 앱의 다른 기능(탭)을 짧게 */
  more?: GuideStep[];
  faq: GuideFaq[];
  /** 알아 두세요(조심할 점, 관리자만 보이는 것 등) */
  notes: string[];
  /** YYYY-MM-DD: 실제 화면과 맞춰 본 날짜 */
  checkedAt: string;
}

export interface GuideApp {
  slug: string;
  title: string;
  /** 실제 앱 주소. 없으면(처음 시작하기) 링크를 걸지 않습니다. */
  href?: string;
  /** 요약본에 보이는 한두 문장 */
  summary: string;
  /** 누가 쓰나요 */
  who: string;
  /** 요약본에 보이는 핵심 3~4줄 */
  quick: string[];
  detail?: GuideDetail;
}

export interface GuideShortcut {
  when: string;
  slug: string;
  where: string;
}

