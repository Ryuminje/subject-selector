export const SEED_DAYS = ["월", "화", "수", "목", "금"];
export const SEED_PERIODS = [1, 2, 3, 4, 5, 6, 7];

export type SeedRow = { teacher: string } & Record<string, string>;

const row = (teacher: string, lessons: Record<string, string>): SeedRow => {
  const r: SeedRow = { teacher };
  for (const day of SEED_DAYS) for (const p of SEED_PERIODS) r[`${day}${p}`] = "";
  return Object.assign(r, lessons);
};

